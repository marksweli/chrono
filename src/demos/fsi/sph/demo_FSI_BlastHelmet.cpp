// SPH simulation of a combat helmet under blast loading from a C4 explosion.
//
// A combat helmet (rigid body with sphere approximation) is subjected to the
// blast wave generated by 14 kg of C4 explosive at a standoff distance of
// 6.1 m.  The explosion source is NOT modeled explicitly.  Instead, empirical
// formulas are used to characterise the blast wave:
//
//   * Hopkinson-Cranz scaled distance  Z = R / W_TNT^(1/3)
//   * Kinney & Graham (1985) formulas for peak overpressure (Pso) and
//     positive-phase duration (td)
//   * Friedlander equation for the pressure-time history:
//       P(t) = Pso * (1 - t/td) * exp(-b * t/td),   0 <= t <= td
//
// The blast wave is represented as a spatial initial-condition snapshot applied
// to the SPH air particles that surround the helmet at simulation time t = 0.
// Particles already in the blast region (x < 0, blast travelling in +x) are
// initialised with the Friedlander pressure and the corresponding particle
// velocity from the Rankine-Hugoniot approximation.  The SPH solver propagates
// the resulting pressure field and computes the forces on the helmet BCE
// markers.
//
// A CSV file "pressure_time_history.csv" is written to the output directory
// with columns:
//   time(s), P_friedlander(Pa), FSI_Fx(N), FSI_Fy(N), FSI_Fz(N),
//   helmet_pos_x(m), helmet_vel_x(m/s)
//
// Demo parameters correspond to:
//   - Explosive mass  : 14 kg C4
//   - TNT equivalence : 1.19  (mass basis)
//   - Standoff        : 6.1 m
//   - Blast direction : +X
//
// Reference values (Kinney & Graham 1985):
//   Z   ≈ 2.38 m/kg^(1/3)
//   Pso ≈ 138  kPa
//   td  ≈ 3.52 ms
// =============================================================================

